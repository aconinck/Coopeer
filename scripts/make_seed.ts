// Builds supabase/seed.sql from the demo data in src/state/mockData.ts.
// Game times are written relative to now() so the demo always has something live and later today.
// Run: node scripts/make_seed.ts   (Node 22.6+ strips the types)
import { writeFileSync } from 'node:fs';
import { clubs, makeGames, places } from '../src/state/mockData.ts';

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[]) => `array[${v.map(q).join(', ')}]::text[]`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const now = new Date();
const games = makeGames(now);
const rel = (d: Date) => `now() + interval '${Math.round((d.getTime() - now.getTime()) / 1000)} seconds'`;

const people = new Map<string, string>();
for (const c of clubs) for (const m of c.members) people.set(m.id, m.name);
for (const g of games) for (const m of [...g.going, ...g.declined, ...g.noResponse]) people.set(m.id, m.name);
people.delete('me');

const lines: string[] = [
  '-- Generated by scripts/make_seed.ts. Demo data for Bentonville, AR. Safe to re-run.',
  'begin;',
  `delete from public.rsvps where game_id in (${games.map((g) => q(g.id)).join(', ')}) and user_id like 'm%' and user_id not like '%-%';`,
  '',
];

for (const [id, name] of people) {
  lines.push(`insert into public.profiles (id, name) values (${q(id)}, ${q(name)}) on conflict (id) do update set name = excluded.name;`);
}
lines.push('');

for (const p of places) {
  lines.push(
    `insert into public.places (id, kind, name, address, latitude, longitude, sports, photos) values (${q(p.id)}, ${q(p.kind)}, ${q(p.name)}, ${q(p.address)}, ${p.latitude}, ${p.longitude}, ${arr(p.sports)}, ${json(p.photos ?? [])}) on conflict (id) do update set kind = excluded.kind, name = excluded.name, address = excluded.address, latitude = excluded.latitude, longitude = excluded.longitude, sports = excluded.sports, photos = excluded.photos;`,
  );
}
lines.push('');

for (const c of clubs) {
  lines.push(
    `insert into public.clubs (id, name, sport, home_place_id, cadence, about, links, monthly_price, level, code, verified) values (${q(c.id)}, ${q(c.name)}, ${q(c.sport)}, ${q(c.homePlaceId)}, ${q(c.cadence)}, ${q(c.about)}, ${json(c.links)}, ${c.monthlyPrice}, ${q(c.level)}, ${q(c.code)}, ${c.verified ? 'true' : 'false'}) on conflict (id) do update set name = excluded.name, cadence = excluded.cadence, about = excluded.about, links = excluded.links, monthly_price = excluded.monthly_price, level = excluded.level, verified = excluded.verified;`,
  );
  c.members.forEach((m, i) => {
    if (m.id === 'me') return;
    lines.push(`insert into public.club_members (club_id, user_id, role) values (${q(c.id)}, ${q(m.id)}, ${q(i === 0 ? 'admin' : 'member')}) on conflict do nothing;`);
  });
}
lines.push('');

for (const g of games) {
  lines.push(
    `insert into public.games (id, sport, place_id, club_id, title, details, starts_at, ends_at, capacity, drop_in_price, level, is_canceled) values (${q(g.id)}, ${q(g.sport)}, ${q(g.placeId)}, ${q(g.clubId)}, ${q(g.title)}, ${q(g.details)}, ${rel(g.start)}, ${rel(g.end)}, ${g.capacity}, ${g.dropInPrice}, ${q(g.level)}, ${g.isCanceled ? 'true' : 'false'}) on conflict (id) do update set starts_at = excluded.starts_at, ends_at = excluded.ends_at, title = excluded.title, details = excluded.details, capacity = excluded.capacity, is_canceled = excluded.is_canceled;`,
  );
  const rsvp = (members: { id: string }[], status: string) =>
    members.filter((m) => m.id !== 'me').forEach((m) => lines.push(`insert into public.rsvps (game_id, user_id, status) values (${q(g.id)}, ${q(m.id)}, ${q(status)}) on conflict do nothing;`));
  rsvp(g.going, 'going');
  rsvp(g.declined, 'declined');
  rsvp(g.noResponse, 'invited');
}

lines.push('', 'commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'));
console.log(`seed.sql: ${people.size} people, ${places.length} places, ${clubs.length} clubs, ${games.length} games`);
